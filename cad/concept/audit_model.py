"""Audit the concept model against the parts registry and the build guides.

Checks: (1) every registry part with qty > 0 is modelled, housed in a modelled enclosure,
or explicitly not modelled (consumable/kit); (2) key dimensions match the guides;
(3) no solid of one assembly intersects a solid of another (AABB pre-check, then exact
boolean volume). Writes docs/logs/MODEL_AUDIT.md and exits 1 on any failure.
Run: /home/user/.venvs/cad/bin/python cad/concept/audit_model.py
"""
import csv, itertools, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
import cell_concept as cc

ROOT = Path(__file__).resolve().parents[2]
cell = cc.build()
leaves = []  # (assembly, label, shape)
for a in cell.children:
    for s in a.children:
        leaves.append((a.label, s.label, s))
labels = " | ".join(l for _, l, _ in leaves)
parts = [r for r in csv.DictReader(open(ROOT / "docs/spine/parts.csv", encoding="utf-8")) if float(r["qty"]) > 0]
NOT_MODELLED = {"P-ST00-002": "fastener kit (bd_warehouse fasteners at LOD2)", "P-ST00-003": "cabling (swept paths at LOD2)",
                "P-ST00-005": "shop 3D printer, outside the cell", "P-ST02-002": "blade consumables",
                "P-ST05-005": "needles and thread consumables"}
fails, rows = [], []
for r in parts:
    pid = r["part_id"]
    if pid in labels: status = "modelled"
    elif pid in NOT_MODELLED: status = "not modelled: " + NOT_MODELLED[pid]
    else: status = "MISSING"; fails.append(f"{pid} {r['description'][:50]} not in model")
    rows.append((pid, r["description"][:60], status))

def bb(label_sub):
    for _, l, s in leaves:
        if label_sub in l: return s.bounding_box()
    fails.append(f"dimension check: no solid labelled '{label_sub}'"); return None
dims = []
def check(name, got, want, tol):
    ok = abs(got - want) <= tol; dims.append((name, round(got), want, tol, ok))
    if not ok: fails.append(f"dimension {name}: {got:.0f} mm vs {want} mm (tol {tol})")
b = bb("A00 back guard panel");        b and check("guarded envelope length X (panel + posts)", b.size.X + 60, 6000, 10)
b = bb("A00 left guard panel");        b and check("guarded envelope depth Y (panel + posts)", b.size.Y + 60, 3000, 10)
b = bb("A04 Festo EGC-120 X axis");    b and check("gantry X beam span (stroke ~2100 + carriage)", b.size.X - 120, 2130, 20)
b = bb("A04 Festo EGC-80 Y axis");     b and check("gantry Y beam span (>= 1500 stroke + carriage)", b.size.Y - 120, 1805, 20)
b = bb("A02 vacuum conveyor felt belt"); b and check("cutter bed width Y (TK4S-2516 1.6 m bed + frame)", b.size.Y, 1650, 20)
b = bb("A02 vacuum conveyor felt belt"); b and check("cutter cutting-zone length X (2.5 m)", b.size.X, 2500, 10)
b = bb("A04 7th-axis rail 1");         b and check("7th-axis track length (~3.2 m stroke)", b.size.X, 3600, 20)
b = bb("A07 backlight tiles");         b and check("inspection backlight field X", b.size.X, 900, 120)
b = bb("A01 fabric roll");             b and check("roll face width (1.8 m web + 0.1 m)", b.size.Y, 1900, 10)

# collisions between different assemblies (exact)
SKIP = re.compile(r"floor|guard panel|interlocked door|fabric web|panel$|sleeve [LR]$|rib strip|finished tee|kit |cut |UR10e (shoulder|upper arm|forearm|wrist)|Robotiq|GelSight|RealSense")
coll = []
items = [(a, l, s, s.bounding_box()) for a, l, s in leaves if not SKIP.search(l)]
for (a1, l1, s1, b1), (a2, l2, s2, b2) in itertools.combinations(items, 2):
    if a1 == a2: continue
    if (b1.min.X < b2.max.X - 1 and b2.min.X < b1.max.X - 1 and b1.min.Y < b2.max.Y - 1 and b2.min.Y < b1.max.Y - 1
            and b1.min.Z < b2.max.Z - 1 and b2.min.Z < b1.max.Z - 1):
        v = (s1 & s2).volume
        if v > 1e3:  # > 1 cm^3
            coll.append((l1, l2, round(v / 1e3))); fails.append(f"collision: {l1} x {l2} ({v/1e3:.0f} cm3)")

out = ["# Model audit", "", "Generated by `cad/concept/audit_model.py` against `docs/spine/parts.csv` and the build guides.", "",
       f"Result: **{'PASS' if not fails else 'FAIL'}** ({len(fails)} issue(s))", "", "## Parts coverage", "",
       "| Part | Description | Status |", "|---|---|---|"] + [f"| {a} | {b} | {c} |" for a, b, c in rows]
out += ["", "## Dimensions", "", "| Check | Model mm | Guide mm | Tolerance | OK |", "|---|---|---|---|---|"] + \
       [f"| {n} | {g} | {w} | ±{t} | {'yes' if ok else 'NO'} |" for n, g, w, t, ok in dims]
out += ["", "## Collisions between assemblies", ""] + ([f"- {a} × {b}: {v} cm³" for a, b, v in coll] or ["None."])
(ROOT / "docs/logs/MODEL_AUDIT.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(fails) or "PASS"); sys.exit(1 if fails else 0)
